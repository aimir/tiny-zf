"""Propose a finite instruction certificate; Lean checks every row independently.

The expanded control-flow graph is extracted from the selected instruction tree.
No assertion in this producer is a formal assumption: the Lean file checks the
literal transitions, successor paths, register-space bounds, and startup prefix.
"""
from pathlib import Path


def range_certificate(size: int, chunk: int = 32) -> list[str]:
    """Bound elaborator state while retaining one kernel check for every row.

    These private lemmas are mechanically indexed certificate batches, not
    separate mathematical claims. They deliberately stay in the same file.
    """
    lines = []
    for lo in range(0, size, chunk):
        count = min(chunk, size-lo)
        lines += [f'/-- Kernel-checked rows {lo}–{lo+count-1}; a bounded elaboration batch.',
                  ' This private certificate is assembled into `checked` below. -/',
                  f'private theorem rows{lo} : checkRange checkRow {lo} {count} = true := by']
        for i in range(lo, lo+count):
            lines += [f'  apply checkRange_step checkRow {i} {lo+count-i-1}',
                      '  · decide +kernel']
        lines += ['  rfl', '']
    lines += ['/-- Every row is checked by the kernel. The private batches bound',
              ' elaborator memory and together cover the entire table exactly. -/',
              f'theorem checked : checkRange checkRow 0 {size} = true := by']
    for lo in range(0, size, chunk):
        count = min(chunk, size-lo)
        lines += [f'  apply checkRange_join checkRow {lo} {count} {size-lo-count}',
                  f'  · exact rows{lo}']
    lines += ['  rfl', '']
    return lines


def program_source(root: Path, record: dict) -> str:
    from joint import build_joint, decode
    from instruction_tree import read_record
    from register_check import compile_fragment

    machine = build_joint(
        decode(record), sharing=record['shared_operations'], grammar=record['grammar'],
        formula_choices=record['formula_choices'],
        instruction_tree=read_record(record, root / 'candidates'), decoder=record['decoder'])
    first, cfg = compile_fragment(machine, machine.find_seq('main().0'), terminal='return')
    leaves = {}

    def visit(value, path):
        if isinstance(value, int):
            visit(machine.sequences[value].seq, path)
        elif isinstance(value, tuple):
            visit(value[0], path + (0,))
            visit(value[1], path + (1,))
        else:
            leaves[path] = value

    visit(machine.find_seq('main().0'), ())
    paths = sorted(leaves)
    indices = {p: i for i, p in enumerate(paths)}
    size = len(paths)
    assert size == 6741
    registers = ['prooflist', 'nextproof', 'topwff', 'wffstack', 'axiomcode',
                 'param1', 'param2', 'param3', 'scratch1', 'scratch2']

    def index(path):
        if path == (1,):
            path = first
        assert path[0] == 0
        return indices[path[1:]]

    lines = [
        'import TinyZF.Tape.Program', '',
        'set_option maxRecDepth 16384', 'set_option maxHeartbeats 0', '',
        '/-! # Checked instruction graph of the 308-state candidate', '',
        'Generated by `formal/tools/generate.py`. The rows are proposed certificates,',
        'not axioms. Every path is checked against the literal transition table;',
        'every successor is checked against binary pointer arithmetic. The 117-step',
        'prefix establishes enough space for the entire unbounded run.',
        '',
        'The source-interpreter connection is a separate theorem. This module',
        'establishes only the literal tape-to-primitive-register-graph connection. -/',
        'namespace TinyZF.Tape.Candidate', 'open Framework', '',
        '/-- Decode a fixed-width binary numeral, preserving leading zero bits. -/',
        'private def revBits : Nat → Nat → List Bool',
        '  | 0, _ => []',
        '  | k+1, v => (v % 2 == 1) :: revBits k (v/2)', '',
        '/-- Decode one compact certificate row. Successor indices are reduced',
        ' modulo the table size; all resulting routing is checked below. -/',
        f'private def row (width value : Nat) (op : Operation) (next zeroTarget : Nat) : Entry {size} :=',
        f'  ⟨(revBits width value).reverse, op, ⟨next % {size}, Nat.mod_lt _ (by decide)⟩,',
        f'    ⟨zeroTarget % {size}, Nat.mod_lt _ (by decide)⟩⟩', '',
        '/- Expanded leaf paths, operations, and successors of the selected',
        ' shared instruction DAG. Row numbers are control-flow locations.',
        ' Private blocks of 64 rows bound elaboration and lookup costs; they',
        ' are data partitions within one file, not additional proof assumptions. -/', '']
    for i, path in enumerate(paths):
        leaf = leaves[path]
        instruction = cfg[(0,) + path]
        if leaf == 'halt':
            op, normal, zero = '.halt', 0, 0
        elif leaf.startswith('_'):
            kind, level = leaf[1:].split('.')
            op = f'.{kind}Op {level}'
            normal = zero = index(instruction[1])
        else:
            _, name, kind = leaf.split('.')
            op = f'.reg {str(kind == "decnz").lower()} {registers.index(name)}'
            normal, zero = index(instruction[2]), index(instruction[3])
        bits = ''.join(map(str, path))
        if i % 64 == 0:
            lines += [f'/-- Certificate rows {i} through {min(i+63,size-1)}. -/',
                      f'private def block{i//64} : Array (Entry {size}) := #[']
        lines.append(f'    row {len(path)} {int(bits, 2)} ({op}) {normal} {zero}' + (',' if i+1 < size and (i+1) % 64 else ''))
        if (i+1) % 64 == 0 or i+1 == size:
            lines += [']', '']
    lines += ['/-- All certificate blocks in control-flow row order. -/',
        f'def table : Array (Array (Entry {size})) := #[',
        '  ' + ', '.join(f'block{i}' for i in range((size+63)//64)) + ']', '',
        '/-- The primitive register program extracted from these checked rows. -/',
        f'def program : Program {size} := ⟨fun i =>',
        f'  ((table[i.val/64]?.getD #[])[i.val%64]?).getD (row 0 0 .halt 0 0), {index(first)}⟩', '',
        '/-- Static per-row checks: actual tape execution, correct successor',
        ' dispatch, and a universal 108-cell pointer-space bound. -/',
        'def checkRow (i : Nat) : Bool :=',
        f'  let e := program.entry ⟨i % {size}, Nat.mod_lt _ (by decide)⟩',
        '  checkAdmissible e.path e.operation && checkRoutes program e &&',
        '    decide (e.path.length+e.operation.gap ≤ 108)', '',
        '']
    lines += range_certificate(size)
    lines += [        '/-- All literal paths and all branch targets are formally certified. -/',
        'theorem certified : program.Certified := by',
        '  apply Program.certified_of_check', '  intro i',
        '  have h := checkRange_sound checked i.val (by omega) i.isLt',
        '  simp only [checkRow, Nat.mod_eq_of_lt i.isLt, Bool.and_eq_true,',
        '    decide_eq_true_eq] at h',
        '  simpa only [Bool.and_eq_true] using h.1', '',
        '/-- The maximum path plus selector requirement is at most 108 cells. -/',
        'theorem bound : ∀ i, (program.entry i).path.length+(program.entry i).operation.gap ≤ 108 := by',
        '  intro i',
        '  have h := checkRange_sound checked i.val (by omega) i.isLt',
        '  simp only [checkRow, Nat.mod_eq_of_lt i.isLt, Bool.and_eq_true,',
        '    decide_eq_true_eq] at h',
        '  exact h.2', '',
        '/-- Every instruction of the startup prefix fits in the space then available. -/',
        'theorem startup : ∀ t : Fin 117, program.Fits (iterate program.step t.val program.initial) := by',
        '  decide +kernel', '',
        '/-- The prefix completes at least 90 decrements, giving 108 cells. -/',
        'theorem enough : 108 ≤ 18+(iterate program.step 117 program.initial).credit := by',
        '  decide +kernel', '',
        '/-- The finite prefix and global instruction bound imply safety for',
        ' every later primitive-register step, regardless of register values. -/',
        'theorem space : ∀ t, program.Fits (iterate program.step t program.initial) :=',
        '  program.space_of_prefix 117 108 bound (fun t ht => startup ⟨t,ht⟩) enough', '',
        '/-- The zero-filled initial pointer dispatches to the first instruction. -/',
        'theorem start : PadEq [] (program.entry program.start).path := by decide +kernel', '',
        '/-- Exact unbounded halting equivalence between the initialized literal',
        ' tape and this finite primitive register program. -/',
        'theorem initialized_iff :',
        '    (∃ k, (iterate (Tape.step m) k (boundary [] 0 18 (fun _ => 0))).state = none) ↔',
        '      program.Halts := certified.halts_iff start space', '',
        'end TinyZF.Tape.Candidate', '']
    return '\n'.join(lines)
